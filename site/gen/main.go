// Command gen regenerates site/docs from the canonical docs in the repo.
//
// site/docs used to be a hand-made copy of docs/ (plus README/ACCURACY/SOURCES)
// with the links edited by hand to suit the site's hash router. Two things went
// wrong with that, both observed in this repo:
//
//   - The copies rot the moment a canonical doc is edited, and nothing notices.
//     docs/api.md and site/docs/api.md had already drifted apart in six places.
//   - Hand-editing links loses them. The endpoint table in site/docs/api.md
//     shipped four EMPTY link targets — `[`GET /api/v1/rates`]()` — because the
//     in-page anchors could not survive the site's `#slug` router and were
//     blanked instead of unwrapped.
//
// So the canonical docs are now the single source and site/docs is generated:
// same bytes, with every link rewritten for the site bundle. The tests in
// gen_test.go fail if site/docs drifts from the generator's output or if any
// generated link would be dead in the bundle, so the site cannot ship a stale
// or broken doc.
//
// How links are rewritten (site/docs.html fetches ./docs/<slug>.md and injects
// the rendered HTML into itself, so a link's base URL is site/, not site/docs/):
//
//   - absolute (http, https, mailto, tel, data) — untouched.
//   - a bare in-page anchor such as (#get-apiv1rates) — the LINK IS UNWRAPPED to
//     its plain label. site/docs.html routes on location.hash, so clicking an
//     in-page anchor would silently navigate to a different document.
//   - a relative path that resolves to another shipped page — becomes "#slug",
//     that page's route (any trailing fragment is dropped, for the reason above).
//   - a relative path that ships inside site/ (images, LICENSE.txt) — kept, or
//     redirected through siteAlias when the site ships it under another name.
//   - anything else (repo-root files, source paths, docs/) — becomes an absolute
//     URL into the repository, where it does resolve.
//   - an EMPTY target — a hard error. That is the bug this generator exists to
//     make impossible, so it fails the build rather than being rewritten.
//
// Usage:
//
//	go run ./site/gen      # rewrite site/docs
//	go test ./site/gen     # verify site/docs is current (runs in CI)
package main

import (
	"fmt"
	"os"
	"path"
	"path/filepath"
	"regexp"
	"strings"
)

// repoURL is where links that cannot resolve inside the site bundle are sent.
const repoURL = "https://github.com/vul-os/openrate/blob/main/"

// rawURL serves images that cannot resolve inside the site bundle; a blob URL
// would render as a GitHub page, not an image.
const rawURL = "https://raw.githubusercontent.com/vul-os/openrate/main/"

// banner marks the output as generated. It is an HTML comment, so marked.js
// renders it as nothing.
const banner = "<!-- Generated from %s by `go run ./site/gen`. Do not edit this file — edit the source and regenerate. -->\n"

// page is one generated site doc: a repo-relative source, and the slug it takes
// inside site/docs (which must match the DOCS nav list in site/docs.html).
type page struct {
	src  string
	slug string
}

// pages is what the site bundle ships, in nav order.
var pages = []page{
	{"README.md", "overview"},
	{"docs/api.md", "api"},
	{"docs/configuration.md", "configuration"},
	{"docs/library.md", "library"},
	{"docs/graph-model.md", "graph-model"},
	{"docs/interest-rates.md", "interest-rates"},
	{"docs/web-ui.md", "web-ui"},
	{"ACCURACY.md", "accuracy"},
	{"SOURCES.md", "sources"},
}

// notShipped lists canonical docs that deliberately do not go to the site, with
// the reason. TestEveryCanonicalDocIsAccountedFor fails on any doc that is in
// neither this map nor pages, so a new guide cannot be silently missed.
var notShipped = map[string]string{
	"docs/README.md": "GitHub-only index of docs/; the site has its own nav in site/docs.html",
	"CHANGELOG.md":   "release history, read on GitHub",
	"ROADMAP.md":     "planning doc, read on GitHub",
	"SECURITY.md":    "disclosure policy, read on GitHub",
	"tasks.md":       "internal task list, not published",
}

// siteAlias maps a repo-relative asset path onto the name the site bundle ships
// it under, so a canonical doc can reference the repo copy and still resolve on
// the site. site/assets/openrate-mark.svg is byte-identical to assets/openrate.svg.
var siteAlias = map[string]string{
	"assets/openrate.svg": "assets/openrate-mark.svg",
}

// mdLinkRE matches a markdown link or image: optional "!", [label], (target).
var mdLinkRE = regexp.MustCompile(`(!?)\[([^\]]*)\]\(([^)]*)\)`)

// htmlAttrRE matches an href/src attribute in inline HTML.
var htmlAttrRE = regexp.MustCompile(`\b(href|src)="([^"]*)"`)

// fenceRE matches a fenced code-block delimiter; link syntax inside a fence is
// sample text and must not be rewritten.
var fenceRE = regexp.MustCompile("^\\s*(```|~~~)")

func isAbsolute(t string) bool {
	for _, p := range []string{"http://", "https://", "mailto:", "tel:", "data:", "//"} {
		if strings.HasPrefix(t, p) {
			return true
		}
	}
	return false
}

// slugFor reports the site slug for a repo-relative path, if it ships.
func slugFor(repoRel string) (string, bool) {
	for _, p := range pages {
		if p.src == repoRel {
			return p.slug, true
		}
	}
	return "", false
}

// shipsInSite reports whether path p (relative to site/) exists in the bundle.
func shipsInSite(root, p string) bool {
	st, err := os.Stat(filepath.Join(root, "site", filepath.FromSlash(p)))
	return err == nil && !st.IsDir()
}

// rewriteTarget maps one link target from a canonical doc to the form it must
// take in the site bundle. unwrap==true means the link should lose its target
// entirely and render as plain text.
func rewriteTarget(root, srcPath, target string, isImage bool) (out string, unwrap bool, err error) {
	target = strings.TrimSpace(target)
	if target == "" {
		return "", false, fmt.Errorf("EMPTY link target — write a real target, or plain text with no link at all")
	}
	if isAbsolute(target) {
		return target, false, nil
	}
	// A bare in-page anchor: site/docs.html routes on location.hash, so this
	// would navigate to another document. Drop the link, keep the words.
	if strings.HasPrefix(target, "#") {
		return "", true, nil
	}

	file, frag := target, ""
	if i := strings.IndexByte(target, '#'); i != -1 {
		file, frag = target[:i], target[i:]
	}
	_ = frag // deliberately dropped: the site's hash is the route, not an anchor

	srcDir := path.Dir(filepath.ToSlash(srcPath))
	if srcDir == "." {
		srcDir = ""
	}
	rel := path.Clean(path.Join(srcDir, file))

	if slug, ok := slugFor(rel); ok {
		return "#" + slug, false, nil
	}
	if alias, ok := siteAlias[rel]; ok && shipsInSite(root, alias) {
		return alias, false, nil
	}
	if shipsInSite(root, rel) {
		return rel, false, nil
	}
	if isImage {
		return rawURL + rel, false, nil
	}
	return repoURL + rel, false, nil
}

// rewriteLine rewrites every markdown link and inline-HTML href/src on one line.
func rewriteLine(root, srcPath, line string) (string, error) {
	var firstErr error

	line = mdLinkRE.ReplaceAllStringFunc(line, func(m string) string {
		g := mdLinkRE.FindStringSubmatch(m)
		bang, label, target := g[1], g[2], g[3]
		// A target may carry a title: (url "title"). Keep the title.
		url, title := target, ""
		if i := strings.IndexAny(target, " \t"); i != -1 {
			url, title = target[:i], target[i:]
		}
		out, unwrap, err := rewriteTarget(root, srcPath, url, bang == "!")
		if err != nil {
			if firstErr == nil {
				firstErr = fmt.Errorf("%w (link text %q)", err, label)
			}
			return m
		}
		if unwrap {
			if bang == "!" { // an image with a fragment target is meaningless
				return label
			}
			return label
		}
		return bang + "[" + label + "](" + out + title + ")"
	})

	line = htmlAttrRE.ReplaceAllStringFunc(line, func(m string) string {
		g := htmlAttrRE.FindStringSubmatch(m)
		attr, target := g[1], g[2]
		out, unwrap, err := rewriteTarget(root, srcPath, target, attr == "src")
		if err != nil {
			if firstErr == nil {
				firstErr = err
			}
			return m
		}
		if unwrap {
			return attr + `="#"`
		}
		return attr + `="` + out + `"`
	})

	return line, firstErr
}

// render produces the generated bytes for one page.
func render(root, srcPath, body string) (string, error) {
	var b strings.Builder
	b.WriteString(fmt.Sprintf(banner, filepath.ToSlash(srcPath)))

	inFence := false
	lines := strings.Split(body, "\n")
	for i, line := range lines {
		if fenceRE.MatchString(line) {
			inFence = !inFence
		} else if !inFence {
			out, err := rewriteLine(root, srcPath, line)
			if err != nil {
				return "", fmt.Errorf("%s:%d: %w", srcPath, i+1, err)
			}
			line = out
		}
		b.WriteString(line)
		if i < len(lines)-1 {
			b.WriteByte('\n')
		}
	}
	return b.String(), nil
}

// generate reads every source page under root and returns slug.md -> content.
func generate(root string) (map[string]string, error) {
	out := make(map[string]string, len(pages))
	for _, p := range pages {
		body, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(p.src)))
		if err != nil {
			return nil, fmt.Errorf("read %s: %w", p.src, err)
		}
		rendered, err := render(root, p.src, string(body))
		if err != nil {
			return nil, err
		}
		out[p.slug+".md"] = rendered
	}
	return out, nil
}

// findRoot walks up from dir to the module root.
func findRoot(dir string) (string, error) {
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("no go.mod above the working directory")
		}
		dir = parent
	}
}

func main() {
	cwd, err := os.Getwd()
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
	root, err := findRoot(cwd)
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
	files, err := generate(root)
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
	dir := filepath.Join(root, "site", "docs")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
	for name, body := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(body), 0o644); err != nil {
			fmt.Fprintln(os.Stderr, "gen:", err)
			os.Exit(1)
		}
	}
	fmt.Printf("gen: wrote %d docs to site/docs\n", len(files))
}
